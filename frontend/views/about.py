"""About: what ConferAtlas is, that the demo data is synthetic, and how the numbers are calculated."""
from __future__ import annotations

from datetime import date
from types import SimpleNamespace

import streamlit as st

from frontend import client
from frontend.components.data_source import call, using_uploaded_data
from frontend.components.layout import page_header


def render() -> None:
    page_header("About ConferAtlas", "What this app is, where the data comes from and how every number is "
                "calculated.", icon=":material/info:")
    about = call(client.about, show_errors=False)
    p = SimpleNamespace(**about["portfolio"]) if about is not None else None

    if using_uploaded_data():
        st.info("You are viewing **your uploaded data**. The notes below on the demo data do not apply to it.",
                icon=":material/upload_file:")
    else:
        st.warning(
            "**The data in this demo is synthetic.** Every event, sponsor, attendee, session and comment was "
            "generated by a script (`scripts/generate_data.py`, fixed seed 42) to show how ConferAtlas works. "
            "Company and person names are invented, and any resemblance to real organisations or people is "
            "coincidental. Do not use these figures to make real decisions.",
            icon=":material/science:",
        )

    if p is not None and p.events:
        p.first_date, p.last_date = date.fromisoformat(p.first_date), date.fromisoformat(p.last_date)
        st.markdown(
            f"The {'uploaded' if using_uploaded_data() else 'demo'} dataset covers **{p.events} events** from "
            f"{p.first_date:%B %Y} to {p.last_date:%B %Y}, with **{p.registrations:,} registrations**, "
            f"**{p.unique_sponsors} sponsors** and **{p.sessions:,} sessions**.")
    elif p is not None:
        st.markdown("The current dataset has no events yet.")

    st.subheader("What ConferAtlas does", anchor=False)
    st.markdown(
        "ConferAtlas helps a conference organiser show sponsors how past events performed: who attended, how "
        "engaged they were, and what sponsors got for their money, especially leads against target. Use the "
        "**filters in the sidebar** to narrow every page to a date range, event type, format, city, event or "
        "sponsor. The chips under each page title show what is applied.")

    st.subheader("How the numbers are calculated", anchor=False)
    st.markdown("""
- **Show-up rate:** attendees as a share of confirmed (not cancelled) registrations.
- **NPS:** approximated from 1-5 session ratings (5 = promoter, 4 = passive, 1-3 = detractor), because the data has no 0-10 "would you recommend" question.
- **Sponsor revenue and cost per lead:** each sponsor has one contract value, split evenly across the events they sponsored, then divided by the leads they got.
- **Leads vs target:** leads recorded for a sponsor at an event against that sponsorship's target. Below 80% is flagged.
- **Renewal status:** derived from history. *Renewed* means the sponsor sponsored in more than one year; sponsors whose first event is in the last 12 months of data are *New* (too early to tell).
- **Booth visits:** recorded per attendee per session, without saying whose booth, so they are event-wide traffic.
- **Returning attendees:** people who attended an earlier event, judged on the full history.
- **Period comparisons:** a date range is compared with the equal-length period just before it.
""")

    st.subheader("AI features and privacy", anchor=False)
    status = client.status()
    st.markdown(
        f"AI features (feedback analysis, the portfolio chat, AI insights and sponsor reports) use "
        f"`{status['model']}` through LangChain and need an API key in `.env`. "
        f"{'A key is configured.' if status['llm_configured'] else 'No key is configured, so they are off; everything else works.'} "
        "Portfolio chat and reports receive computed aggregates, never individual attendee or lead records. "
        "Feedback analysis sends comment text after common contact details are redacted; review real comments "
        "for remaining names or other identifiers before sending. Numeric checks preserve signs and units, "
        "but still require a human review before sharing reports. The **AI usage** panel at the "
        "bottom of the sidebar shows each request's tokens, latency and estimated cost.")

    st.subheader("Using your own data", anchor=False)
    st.markdown(
        "Open **Data source** in the sidebar and upload the eight CSV files (events, sponsors, sponsorships, "
        "registrations, sessions, engagement, leads, feedback). They are checked for missing columns, wrong "
        "types and bad dates before anything is shown. The README in the project folder lists every column.")
